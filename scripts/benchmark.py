"""Run the context-scaling benchmark and write docs/BENCHMARK_REPORT.md."""

from __future__ import annotations

import sys
import time
from pathlib import Path

from skillstate.benchmarks.scaling import render_report, run_benchmark

steps = int(sys.argv[1]) if len(sys.argv) > 1 else 1000
started = time.time()
report = run_benchmark(steps=steps, observation_chars=400)
text = render_report(report) + f"\n_Generated by `scripts/benchmark.py {steps}` in {time.time() - started:.1f}s._\n"
out = Path("docs/BENCHMARK_REPORT.md")
out.write_text(text, encoding="utf-8")
print(text)
print(f"wrote {out}")
sys.exit(0 if report["bounded"] else 1)
